# ## 11. Do higher fertiliser and pesticide inputs buy higher yield?
#
# This section examines associations, not causal effects. Raw total input values can be misleading because larger cultivated areas tend to use more inputs. We therefore calculate input intensity per unit area and compare it with yield. The analysis is descriptive and does not establish that changing an input will cause yield to change.


