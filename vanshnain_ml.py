# ## 13. Permutation feature importance
#
# Permutation importance estimates how much held-out MAE worsens when a feature is shuffled. The hold-out scorer converts model predictions from log1p back to original yield units. The held-out target is already in original units, so it is not transformed again. Importance is calculated on the original input columns using the held-out years.


perm = permutation_importance(
    best_model, X_test, y_test,
    scoring=holdout_yield_mae_scorer,
    n_repeats=5,
    random_state=RANDOM_STATE,
    n_jobs=-1
)
importance_df = pd.DataFrame({
    "Feature": feature_cols,
    "Importance_mean": perm.importances_mean,
    "Importance_std": perm.importances_std
}).sort_values("Importance_mean", ascending=False)

display(importance_df)
plt.figure(figsize=(8, 5))
plt.barh(importance_df["Feature"], importance_df["Importance_mean"])
plt.gca().invert_yaxis()
plt.title("Permutation importance on 2016–2020 hold-out")
plt.xlabel("Increase in MAE when shuffled (original yield units)")
plt.tight_layout()
plt.show()


