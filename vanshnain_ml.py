# ## 5. Define the time-based train/test split
#
# All records through 2015 are used for training. Records from 2016 onward are held out for testing. This is a more realistic test of forecasting into later years than a random split.
#
# The features follow the research question: area, annual rainfall, fertiliser, pesticide, crop, season and state. `Production` and `Crop_Year` are not predictors.


feature_cols = [
    "Area", "Annual_Rainfall", "Fertilizer", "Pesticide",
    "Crop", "Season", "State"
]
numeric_features = ["Area", "Annual_Rainfall", "Fertilizer", "Pesticide"]
categorical_features = ["Crop", "Season", "State"]

train_df = df[df["Crop_Year"] <= TRAIN_END_YEAR].copy()
test_df = df[df["Crop_Year"] > TRAIN_END_YEAR].copy()

if train_df.empty or test_df.empty:
    raise ValueError(
        f"Time split produced an empty set. Dataset years: "
        f"{df['Crop_Year'].min()}–{df['Crop_Year'].max()}. "
        "Adjust TRAIN_END_YEAR if needed."
    )

X_train, X_test = train_df[feature_cols], test_df[feature_cols]
y_train = np.log1p(train_df["Yield"].values)
y_test = test_df["Yield"].values

print(f"Train: {len(train_df):,} rows, years {train_df.Crop_Year.min()}–{train_df.Crop_Year.max()}")
print(f"Test : {len(test_df):,} rows, years {test_df.Crop_Year.min()}–{test_df.Crop_Year.max()}")


# ## 6. Preprocessing and outlier treatment
#
# A quantile clipper learns the 1st and 99th percentile limits from the **training set only**, then applies those limits to both train and test data. This reduces the influence of extreme input values without allowing test data to influence preprocessing.
#
# Numeric variables are median-imputed and standardised. Categorical variables are mode-imputed and one-hot encoded. Polynomial features are added only to numeric variables for the polynomial model.


class QuantileClipper(BaseEstimator, TransformerMixin):
    def __init__(self, lower=0.01, upper=0.99):
        self.lower = lower
        self.upper = upper

    def fit(self, X, y=None):
        X = np.asarray(X, dtype=float)
        self.lower_bounds_ = np.nanquantile(X, self.lower, axis=0)
        self.upper_bounds_ = np.nanquantile(X, self.upper, axis=0)
        return self

    def transform(self, X):
        X = np.asarray(X, dtype=float)
        return np.clip(X, self.lower_bounds_, self.upper_bounds_)

numeric_preprocess = Pipeline(steps=[
    ("imputer", SimpleImputer(strategy="median")),
    ("clipper", QuantileClipper(0.01, 0.99)),
    ("scaler", StandardScaler())
])

categorical_preprocess = Pipeline(steps=[
    ("imputer", SimpleImputer(strategy="most_frequent")),
    ("onehot", OneHotEncoder(handle_unknown="ignore"))
])

preprocessor = ColumnTransformer(transformers=[
    ("num", numeric_preprocess, numeric_features),
    ("cat", categorical_preprocess, categorical_features)
])

# Polynomial expansion applies to numeric inputs only; categorical features remain one-hot encoded.
polynomial_preprocessor = ColumnTransformer(transformers=[
    ("num", Pipeline(steps=[
        ("imputer", SimpleImputer(strategy="median")),
        ("clipper", QuantileClipper(0.01, 0.99)),
        ("poly", PolynomialFeatures(degree=2, include_bias=False)),
        ("scaler", StandardScaler())
    ]), numeric_features),
    ("cat", categorical_preprocess, categorical_features)
])


# ## 7. Train and compare regression models


models = {
    "Dummy Baseline (median)": Pipeline([
        ("preprocess", preprocessor),
        ("model", DummyRegressor(strategy="median"))
    ]),
    "Multiple Linear Regression": Pipeline([
        ("preprocess", preprocessor),
        ("model", LinearRegression())
    ]),
    "Polynomial Regression (degree 2)": Pipeline([
        ("preprocess", polynomial_preprocessor),
        ("model", LinearRegression())
    ]),
    "Ridge Regression": Pipeline([
        ("preprocess", preprocessor),
        ("model", Ridge(alpha=10.0))
    ]),
    "Lasso Regression": Pipeline([
        ("preprocess", preprocessor),
        ("model", Lasso(alpha=0.001, max_iter=20000))
    ]),
    "Decision Tree": Pipeline([
        ("preprocess", preprocessor),
        ("model", DecisionTreeRegressor(
            max_depth=12, min_samples_leaf=5, random_state=RANDOM_STATE
        ))
    ]),
    "k-NN Regressor": Pipeline([
        ("preprocess", preprocessor),
        ("model", KNeighborsRegressor(n_neighbors=10, weights="distance"))
    ])
}

results = []
fitted_models = {}
predictions = {}

for name, pipe in models.items():
    pipe.fit(X_train, y_train)
    pred_log = pipe.predict(X_test)
    pred_yield = np.maximum(0, np.expm1(pred_log))
    predictions[name] = pred_yield
    fitted_models[name] = pipe

    rmse = np.sqrt(mean_squared_error(y_test, pred_yield))
    mae = mean_absolute_error(y_test, pred_yield)
    r2 = r2_score(y_test, pred_yield)
    results.append({"Model": name, "RMSE": rmse, "MAE": mae, "R2": r2})

results_df = pd.DataFrame(results).sort_values("RMSE")
display(results_df)


# ## 8. Time-based cross-validation and hyperparameter tuning
#
# Model selection is performed using expanding-window validation folds built only from the training years. Each validation fold contains later years than its corresponding training fold. The final 2016–2020 hold-out set is not used to choose the model or tune its parameters.
#
# The custom scorer converts predictions back from log1p scale and calculates MAE in the original yield units. A Decision Tree is tuned with GridSearchCV; its best estimator is compared with the baseline and the other candidate pipelines.


# Build expanding-window folds using training years only.
train_years = train_df["Crop_Year"].to_numpy()
temporal_cv_splits = []

for train_end, valid_start, valid_end in [
    (2007, 2008, 2010),
    (2010, 2011, 2013),
    (2013, 2014, 2015)
]:
    train_idx = np.flatnonzero(train_years <= train_end)
    valid_idx = np.flatnonzero(
        (train_years >= valid_start) & (train_years <= valid_end)
    )
    if len(train_idx) == 0 or len(valid_idx) == 0:
        raise ValueError(
            f"Empty temporal CV fold: train <= {train_end}, "
            f"validation {valid_start}-{valid_end}. Check dataset years."
        )
    temporal_cv_splits.append((train_idx, valid_idx))

print("Temporal CV folds (train years -> validation years):")
for train_idx, valid_idx in temporal_cv_splits:
    print(
        f"{train_years[train_idx].min()}-{train_years[train_idx].max()} -> "
        f"{train_years[valid_idx].min()}-{train_years[valid_idx].max()} "
        f"({len(train_idx):,} train, {len(valid_idx):,} validation rows)"
    )

# Scikit-learn scorers are maximised, so return negative MAE.
# Both y and estimator predictions are on log1p scale.
def cv_yield_mae_scorer(estimator, X, y):
    # During CV, y is stored on the log1p scale.
    actual_yield = np.expm1(np.asarray(y))
    predicted_yield = np.maximum(0, np.expm1(estimator.predict(X)))
    return -mean_absolute_error(actual_yield, predicted_yield)

def holdout_yield_mae_scorer(estimator, X, y):
    # The final hold-out target y_test is already on the original yield scale.
    predicted_yield = np.maximum(0, np.expm1(estimator.predict(X)))
    return -mean_absolute_error(np.asarray(y), predicted_yield)

cv_rows = []
for name, estimator in models.items():
    fold_scores = cross_val_score(
        estimator,
        X_train,
        y_train,
        cv=temporal_cv_splits,
        scoring=cv_yield_mae_scorer,
        n_jobs=-1
    )
    cv_rows.append({
        "Model": name,
        "CV_MAE_mean": -fold_scores.mean(),
        "CV_MAE_std": fold_scores.std()
    })

# Tune a Decision Tree using only the temporal CV folds.
tree_search = GridSearchCV(
    estimator=models["Decision Tree"],
    param_grid={
        "model__max_depth": [8, 12, None],
        "model__min_samples_leaf": [3, 5, 10],
        "model__min_samples_split": [2, 10]
    },
    scoring=cv_yield_mae_scorer,
    cv=temporal_cv_splits,
    n_jobs=-1,
    refit=True
)
tree_search.fit(X_train, y_train)

tuned_tree = tree_search.best_estimator_
tuned_name = "Tuned Decision Tree"
fitted_models[tuned_name] = tuned_tree
tuned_pred = np.maximum(0, np.expm1(tuned_tree.predict(X_test)))
predictions[tuned_name] = tuned_pred

cv_rows.append({
    "Model": tuned_name,
    "CV_MAE_mean": -tree_search.best_score_,
    "CV_MAE_std": tree_search.cv_results_["std_test_score"][tree_search.best_index_]
})

cv_results_df = pd.DataFrame(cv_rows).sort_values("CV_MAE_mean").reset_index(drop=True)
display(cv_results_df)

print("Best Decision Tree parameters:", tree_search.best_params_)
print("Selected model by temporal CV:", cv_results_df.iloc[0]["Model"])

# Add the tuned model's final hold-out metrics for reporting only.
results.append({
    "Model": tuned_name,
    "RMSE": np.sqrt(mean_squared_error(y_test, tuned_pred)),
    "MAE": mean_absolute_error(y_test, tuned_pred),
    "R2": r2_score(y_test, tuned_pred)
})
results_df = pd.DataFrame(results).sort_values("RMSE").reset_index(drop=True)
display(results_df)


